import { timingSafeEqual } from 'node:crypto';
import { NextResponse, type NextRequest } from 'next/server';
import {
  emailProviderConfigured,
  processCampaign,
  workerSender
} from '@/features/email-campaigns/server/sender';
import { createAnonClient } from '@/lib/supabase/anon';
import { errorResponse } from '@/lib/validation/http';

// Background sender, called by a scheduler (Vercel Cron, or the GitHub Actions
// workflow email-worker.yml) with `Authorization: Bearer <CRON_SECRET>`. Starts
// the scheduled campaigns that are due and sends pending batches. There is no
// user session: the database calls authenticate with the e-mail worker key
// (LEVELUP_EMAIL_KEY, hashed in the database, generated by LevelUp staff).
// Off (404) until CRON_SECRET, LEVELUP_EMAIL_KEY and the provider key are set.

export const maxDuration = 60;

function authorized(request: NextRequest, secret: string): boolean {
  const given = Buffer.from(request.headers.get('authorization') ?? '');
  const expected = Buffer.from(`Bearer ${secret}`);
  return given.length === expected.length && timingSafeEqual(given, expected);
}

async function run(request: NextRequest) {
  const secret = process.env.CRON_SECRET;
  const key = process.env.LEVELUP_EMAIL_KEY;
  if (!secret || secret.length < 16 || !key || !emailProviderConfigured()) {
    return errorResponse(404, 'not_found');
  }
  if (!authorized(request, secret)) return errorResponse(401, 'unauthorized');

  const db = createAnonClient();
  const { data, error } = await db.rpc('email_worker_due', { p_key: key });
  if (error) {
    console.error('email worker: due list failed', error.code ?? '');
    return errorResponse(500, 'failed');
  }
  const deadline = Date.now() + 45_000;
  let sent = 0;
  const campaigns = (data as string[]) ?? [];
  for (const id of campaigns) {
    const left = deadline - Date.now();
    if (left < 3_000) break;
    try {
      sent += (await processCampaign(workerSender(db, key), id, left)).sent;
    } catch (e) {
      console.error('email worker: campaign failed', (e as { code?: string }).code ?? '');
    }
  }
  return NextResponse.json(
    { campaigns: campaigns.length, sent },
    { headers: { 'Cache-Control': 'no-store' } }
  );
}

export const GET = run;
export const POST = run;
